import assert from "node:assert/strict";
import { createHmac } from "node:crypto";
const { verify, subscriptionPatch } = await import("../api/dodo-webhook.ts");
const secret = "whsec_" + Buffer.from("super-secret-key-1234567890").toString("base64");
const body = JSON.stringify({ type: "subscription.active", data: { subscription_id: "sub_1" } });
const sign = (id, ts, b) => "v1," + createHmac("sha256", Buffer.from("super-secret-key-1234567890")).update(`${id}.${ts}.${b}`).digest("base64");
const ts = String(Math.floor(Date.now() / 1000));
const h = { "webhook-id": "msg_1", "webhook-timestamp": ts, "webhook-signature": sign("msg_1", ts, body) };
assert.equal(verify(body, h, secret), true, "valid signature");
assert.equal(verify(body + " ", h, secret), false, "tampered body");
assert.equal(verify(body, { ...h, "webhook-signature": "v1,AAAA" }, secret), false, "wrong signature");
assert.equal(verify(body, { ...h, "webhook-signature": "v2," + h["webhook-signature"].slice(3) }, secret), false, "wrong version");
assert.equal(verify(body, { ...h, "webhook-signature": "v1,AAAA " + h["webhook-signature"] }, secret), true, "second signature in list");
const old = String(Math.floor(Date.now() / 1000) - 3600);
assert.equal(verify(body, { "webhook-id": "m", "webhook-timestamp": old, "webhook-signature": sign("m", old, body) }, secret), false, "replay window");
assert.equal(verify(body, {}, secret), false, "missing headers");
const next = "2026-12-01T00:00:00Z";
let p = subscriptionPatch("subscription.active", { subscription_id: "s", customer: { email: "a@b.c", customer_id: "c" }, next_billing_date: next });
assert.equal(p.plan, "pro"); assert.equal(p.proUntil.toDate().toISOString(), "2026-12-01T00:00:00.000Z");
p = subscriptionPatch("subscription.active", {}); assert.ok(p.proUntil.toDate() > new Date(Date.now() + 30 * 864e5), "fallback 35 days");
p = subscriptionPatch("payment.succeeded", { subscription_id: "s" }, true); assert.equal(p.plan, "pro");
p = subscriptionPatch("subscription.cancelled", {}); assert.equal(p.plan, "pro"); assert.equal(p.cancelAtPeriodEnd, true); assert.equal("proUntil" in p, false, "cancel keeps paid period");
p = subscriptionPatch("subscription.expired", {}); assert.equal(p.plan, "free"); assert.ok(p.proUntil.toDate() <= new Date());
p = subscriptionPatch("subscription.on_hold", {}); assert.equal(p.plan, "free");
console.log("webhook tests passed");
